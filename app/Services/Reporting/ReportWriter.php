<?php

namespace App\Services\Reporting;

use DOMDocument;
use DOMElement;
use OpenSpout\Common\Entity\Row;
use OpenSpout\Writer\XLSX\Writer as XlsxWriter;
use RuntimeException;

/**
 * Renders a ReportDocument into a downloadable file.
 *
 * Every format leads with the summary and follows it with the supporting data,
 * in the order DICT asked for. CSV and XML are written by hand because both are
 * plain text; the spreadsheet uses the same OpenSpout engine Filament already
 * ships, so no new dependency is added.
 */
class ReportWriter
{
    public const CSV = 'csv';

    public const XLSX = 'xlsx';

    public const XML = 'xml';

    /** @return array<int, string> */
    public static function formats(): array
    {
        return [self::CSV, self::XLSX, self::XML];
    }

    /**
     * @param  array<string, mixed>  $document
     */
    public static function write(string $format, array $document): string
    {
        return match ($format) {
            self::CSV => self::csv($document),
            self::XLSX => self::xlsx($document),
            self::XML => self::xml($document),
            default => throw new RuntimeException("Unsupported report format: {$format}"),
        };
    }

    public static function mimeType(string $format): string
    {
        return match ($format) {
            self::CSV => 'text/csv',
            self::XLSX => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            self::XML => 'application/xml',
            default => 'application/octet-stream',
        };
    }

    /**
     * Summary block, a blank separator, then the supporting rows. A single CSV
     * has no notion of sheets, so the section marker is what makes the file
     * readable rather than a wall of numbers.
     *
     * @param  array<string, mixed>  $document
     */
    private static function csv(array $document): string
    {
        $out = fopen('php://temp', 'r+');

        $line = function (array $cells) use ($out): void {
            fputcsv($out, $cells, ',', '"', '\\');
        };

        $line(['DICT Free Wi-Fi — Survey Report']);
        $line(['Generated', $document['meta']['generated_at']->format('Y-m-d H:i:s')]);
        $line(['Generated by', $document['meta']['generated_by']]);

        $filters = array_filter((array) $document['meta']['filters']);

        $line(['Filters', $filters === [] ? 'All locations, all dates' : json_encode($filters)]);

        $line([]);
        $line(['SUMMARY']);
        $line(['Measure', 'Value', 'Notes']);

        foreach ($document['summary'] as $entry) {
            $line([$entry['label'], $entry['value'] ?? '', $entry['note']]);
        }

        $line([]);
        $line(['BY SITE']);
        $line(['Site', 'Location', 'Responses', 'Rated (n)', 'Average rating', 'Note']);

        foreach ($document['by_site'] as $row) {
            $line([
                $row['label'],
                $row['location'] ?? '',
                $row['responses'],
                $row['rated'],
                $row['average_rating'] ?? '',
                $row['significant'] ? '' : 'small sample',
            ]);
        }

        $line([]);
        $line(['BY SUPPLIER']);
        $line(['Supplier', 'Responses', 'Rated (n)', 'Average rating', 'Note']);

        foreach ($document['by_supplier'] as $row) {
            $line([
                $row['label'],
                $row['responses'],
                $row['rated'],
                $row['average_rating'] ?? '',
                $row['significant'] ? '' : 'small sample',
            ]);
        }

        // The three series behind the PDF charts, as plain rows. A spreadsheet
        // or CSV cannot hold a chart in a way every reader will see, but these
        // numbers are exactly what the graphs are drawn from, so a reader can
        // rebuild or check them.
        $line([]);
        $line(['RATING BREAKDOWN (chart data)']);
        $line(['Stars', 'Responses']);

        foreach ($document['rating_distribution'] as $row) {
            $line([$row['stars'].' star', $row['total']]);
        }

        $line([]);
        $line(['RESPONSES BY DAY (chart data)']);
        $line(['Day', 'Responses', 'Average rating']);

        foreach ($document['daily'] as $row) {
            $line([$row['day'], $row['responses'], $row['average_rating'] ?? '']);
        }

        // Who answered. "Did not answer" is in the figures on purpose: a
        // breakdown that hides the people who skipped the question would read
        // as if everybody had an opinion.
        foreach ([
            ['GENDER (chart data)', $document['by_gender']],
            ['SECTOR (chart data)', $document['by_sector']],
        ] as [$heading, $rows]) {
            $line([]);
            $line([$heading]);
            $line(['Answer', 'Responses', 'Share of all responses']);

            foreach ($rows as $row) {
                $line([
                    $row['label'],
                    $row['total'],
                    $row['share'] === null ? '' : $row['share'].'%',
                ]);
            }
        }

        // Comments per location.
        $line([]);
        $line(['COMMENTS BY LOCATION (chart data)']);
        $line(['Site', 'Location', 'Comments', 'Share of all responses']);

        foreach ($document['comments_by_site'] as $row) {
            $line([
                $row['site_code'],
                $row['site_name'],
                $row['total'],
                $row['share'] === null ? '' : $row['share'].'%',
            ]);
        }

        $line([]);
        $line(['ISSUES REPORTED']);
        $line(['Issue', 'Count']);

        foreach ($document['by_issue'] as $row) {
            $line([str_replace('_', ' ', $row['issue_category']), $row['total']]);
        }

        // Free-text answers. Labelled because, unlike the rest of the file,
        // these are the public's own words and are not scrubbed.
        $line([]);
        $line(['COMMENTS (free text typed by the public - handle as sensitive)']);
        $line(['Reference', 'Site', 'Submitted', 'Rating', 'Question', 'Comment']);

        foreach ($document['comments'] as $c) {
            $line([
                $c['reference'], $c['site_code'], $c['submitted_at'],
                $c['rating'], $c['question'], $c['comment'],
            ]);
        }

        $line([]);
        $line(['RESPONSES (supporting data)']);

        if ($document['truncated']) {
            $line(['Note', sprintf(
                'Showing the %d most recent of %d matching responses. Use the untruncated export for the full set.',
                count($document['responses']),
                $document['total_matched'],
            )]);
        }

        $line(ReportDocument::responseColumns());

        foreach ($document['responses'] as $response) {
            $line(array_values(ReportDocument::responseRow($response)));
        }

        rewind($out);
        $contents = (string) stream_get_contents($out);
        fclose($out);

        // A BOM makes Excel open UTF-8 correctly instead of mangling accented
        // Filipino place names.
        return "\xEF\xBB\xBF".$contents;
    }

    /**
     * Three sheets: summary and charts first, then the comments in the public's
     * own words, then the supporting response rows.
     *
     * @param  array<string, mixed>  $document
     */
    private static function xlsx(array $document): string
    {
        $path = tempnam(sys_get_temp_dir(), 'pulse-report-').'.xlsx';

        $writer = new XlsxWriter;
        $writer->openToFile($path);

        $row = fn (array $cells) => $writer->addRow(Row::fromValues($cells));

        // Sheet 1: the summary.
        $writer->getCurrentSheet()->setName('Summary');

        $row(['DICT Free Wi-Fi — Survey Report']);
        $row(['Generated', $document['meta']['generated_at']->format('Y-m-d H:i:s')]);
        $row(['Generated by', $document['meta']['generated_by']]);

        $filters = array_filter((array) $document['meta']['filters']);
        $row(['Filters', $filters === [] ? 'All locations, all dates' : json_encode($filters)]);
        $row([]);
        $row(['Measure', 'Value', 'Notes']);

        foreach ($document['summary'] as $entry) {
            $row([$entry['label'], $entry['value'] ?? '', $entry['note']]);
        }

        $row([]);
        $row(['By site', 'Location', 'Responses', 'Rated (n)', 'Average rating', 'Note']);

        foreach ($document['by_site'] as $r) {
            $row([
                $r['label'], $r['location'] ?? '', $r['responses'], $r['rated'],
                $r['average_rating'] ?? '', $r['significant'] ? '' : 'small sample',
            ]);
        }

        // Star-by-star split, the series the PDF's rating chart is drawn from.
        $row([]);
        $row(['Rating breakdown', 'Responses']);

        foreach ($document['rating_distribution'] as $r) {
            $row([$r['stars'].' star', $r['total']]);
        }

        // Who answered.
        foreach ([
            ['Gender', $document['by_gender']],
            ['Sector', $document['by_sector']],
        ] as [$heading, $rows]) {
            $row([]);
            $row([$heading, 'Responses', 'Share of all responses']);

            foreach ($rows as $r) {
                $row([$r['label'], $r['total'], $r['share'] === null ? '' : $r['share'].'%']);
            }
        }

        // Comments per location.
        $row([]);
        $row(['Comments by location', 'Comments', 'Share of all responses']);

        foreach ($document['comments_by_site'] as $r) {
            $row([$r['site_code'], $r['total'], $r['share'] === null ? '' : $r['share'].'%']);
        }

        $row([]);
        $row(['By supplier', 'Responses', 'Rated (n)', 'Average rating', 'Note']);

        foreach ($document['by_supplier'] as $r) {
            $row([
                $r['label'], $r['responses'], $r['rated'],
                $r['average_rating'] ?? '', $r['significant'] ? '' : 'small sample',
            ]);
        }

        // Sheet 2: the comments. Their own sheet so they can be shared, or
        // withheld, separately from the numbers.
        $writer->addNewSheetAndMakeItCurrent();
        $writer->getCurrentSheet()->setName('Comments');

        $row(['Free text typed by the public. Handle as sensitive: these are the respondent\'s own words and are not scrubbed.']);
        $row([]);

        if ($document['comments'] === []) {
            $row(['No written comments for these filters.']);
        } else {
            $row(['Reference', 'Site', 'Submitted', 'Rating', 'Question', 'Comment']);

            foreach ($document['comments'] as $c) {
                $row([
                    $c['reference'], $c['site_code'], $c['submitted_at'],
                    $c['rating'], $c['question'], $c['comment'],
                ]);
            }
        }

        // Sheet 3: the supporting data.
        $writer->addNewSheetAndMakeItCurrent();
        $writer->getCurrentSheet()->setName('Responses');

        if ($document['truncated']) {
            $row(['Note', sprintf(
                'Showing the %d most recent of %d matching responses.',
                count($document['responses']),
                $document['total_matched'],
            )]);
            $row([]);
        }

        $row(ReportDocument::responseColumns());

        foreach ($document['responses'] as $response) {
            $row(array_values(ReportDocument::responseRow($response)));
        }

        $writer->close();

        $contents = (string) file_get_contents($path);
        @unlink($path);

        return $contents;
    }

    /**
     * Structured, so another system can read it without parsing prose.
     *
     * Built with DOMDocument rather than string concatenation: place names and
     * free-text comments will contain &, < and quotes, and hand-rolled escaping
     * is how XML exports end up unparseable.
     *
     * @param  array<string, mixed>  $document
     */
    private static function xml(array $document): string
    {
        $dom = new DOMDocument('1.0', 'UTF-8');
        $dom->formatOutput = true;

        $root = $dom->createElement('surveyReport');
        $dom->appendChild($root);

        $add = function (DOMElement $parent, string $name, string|int|null $value) use ($dom): void {
            if ($value === null) {
                return;
            }

            $parent->appendChild($dom->createElement($name, htmlspecialchars((string) $value, ENT_XML1)));
        };

        $meta = $dom->createElement('meta');
        $add($meta, 'generatedAt', $document['meta']['generated_at']->format(DATE_ATOM));
        $add($meta, 'generatedBy', $document['meta']['generated_by']);
        $add($meta, 'positiveThreshold', $document['meta']['positive_threshold']);
        $add($meta, 'minimumSampleSize', $document['meta']['minimum_sample_size']);

        foreach ((array) $document['meta']['filters'] as $key => $value) {
            if ($value !== null && $value !== '') {
                $add($meta, 'filter'.ucfirst($key), $value);
            }
        }

        $root->appendChild($meta);

        $summary = $dom->createElement('summary');

        foreach ($document['summary'] as $entry) {
            $measure = $dom->createElement('measure');
            $measure->setAttribute('name', (string) $entry['label']);
            // A null value is emitted as an empty element, not "0", so a reader
            // can tell "no data" from "zero".
            $measure->appendChild($dom->createElement('value', htmlspecialchars((string) ($entry['value'] ?? ''), ENT_XML1)));
            $measure->appendChild($dom->createElement('note', htmlspecialchars((string) $entry['note'], ENT_XML1)));
            $summary->appendChild($measure);
        }

        $root->appendChild($summary);

        $bySite = $dom->createElement('bySite');

        foreach ($document['by_site'] as $row) {
            $site = $dom->createElement('site');
            $add($site, 'siteCode', $row['label']);
            $add($site, 'location', $row['location'] ?? null);
            $add($site, 'responses', $row['responses']);
            $add($site, 'rated', $row['rated']);
            $add($site, 'averageRating', $row['average_rating']);
            $add($site, 'smallSample', $row['significant'] ? null : 'true');
            $bySite->appendChild($site);
        }

        $root->appendChild($bySite);

        $bySupplier = $dom->createElement('bySupplier');

        foreach ($document['by_supplier'] as $row) {
            $supplier = $dom->createElement('supplier');
            $add($supplier, 'name', $row['label']);
            $add($supplier, 'responses', $row['responses']);
            $add($supplier, 'rated', $row['rated']);
            $add($supplier, 'averageRating', $row['average_rating']);
            $bySupplier->appendChild($supplier);
        }

        $root->appendChild($bySupplier);

        $issues = $dom->createElement('issues');

        foreach ($document['by_issue'] as $row) {
            $issue = $dom->createElement('issue');
            $add($issue, 'category', str_replace('_', ' ', $row['issue_category']));
            $add($issue, 'count', $row['total']);
            $issues->appendChild($issue);
        }

        $root->appendChild($issues);

        // The series the PDF's charts are drawn from, so a downstream reader can
        // verify a graph instead of trusting an image.
        $distribution = $dom->createElement('ratingDistribution');

        foreach ($document['rating_distribution'] as $row) {
            $bucket = $dom->createElement('rating');
            $bucket->setAttribute('stars', (string) $row['stars']);
            $bucket->setAttribute('count', (string) $row['total']);
            $distribution->appendChild($bucket);
        }

        $root->appendChild($distribution);

        // Who answered.
        $demographics = $dom->createElement('demographics');

        foreach ([
            ['gender', $document['by_gender']],
            ['sector', $document['by_sector']],
        ] as [$name, $rows]) {
            $group = $dom->createElement($name);

            foreach ($rows as $row) {
                $entry = $dom->createElement('answer');
                $entry->setAttribute('label', $row['label']);
                $entry->setAttribute('count', (string) $row['total']);
                $entry->setAttribute('share', (string) ($row['share'] ?? ''));
                $group->appendChild($entry);
            }

            $demographics->appendChild($group);
        }

        $root->appendChild($demographics);

        // Comments grouped by location.
        $commentsBySiteXml = $dom->createElement('commentsBySite');

        foreach ($document['comments_by_site'] as $row) {
            $entry = $dom->createElement('site');
            $entry->setAttribute('code', $row['site_code']);
            $entry->setAttribute('name', $row['site_name']);
            $entry->setAttribute('count', (string) $row['total']);
            $entry->setAttribute('share', (string) ($row['share'] ?? ''));
            $commentsBySiteXml->appendChild($entry);
        }

        $root->appendChild($commentsBySiteXml);

        $trend = $dom->createElement('dailyResponses');

        foreach ($document['daily'] as $row) {
            $day = $dom->createElement('day');
            $add($day, 'date', $row['day']);
            $add($day, 'responses', $row['responses']);
            $add($day, 'averageRating', $row['average_rating']);
            $trend->appendChild($day);
        }

        $root->appendChild($trend);

        // Free-text answers as their own element so a consumer can extract the
        // comments without parsing the response rows, and can see they are
        // unsanitised public text.
        $comments = $dom->createElement('comments');
        $comments->setAttribute('sensitive', 'true');
        $comments->setAttribute('note', 'Free text typed by the public. Not scrubbed.');

        foreach ($document['comments'] as $row) {
            $comment = $dom->createElement('comment');
            $add($comment, 'reference', $row['reference']);
            $add($comment, 'site', $row['site_code']);
            $add($comment, 'submittedAt', $row['submitted_at']);
            $add($comment, 'question', $row['question']);
            $add($comment, 'text', $row['comment']);
            $comments->appendChild($comment);
        }

        $root->appendChild($comments);

        $responses = $dom->createElement('responses');
        $responses->setAttribute('totalMatched', (string) $document['total_matched']);
        $responses->setAttribute('included', (string) count($document['responses']));
        $responses->setAttribute('truncated', $document['truncated'] ? 'true' : 'false');

        foreach ($document['responses'] as $response) {
            $node = $dom->createElement('response');

            foreach (ReportDocument::responseRow($response) as $column => $value) {
                if ($value !== null && $value !== '') {
                    $add($node, $column, $value);
                }
            }

            $responses->appendChild($node);
        }

        $root->appendChild($responses);

        return (string) $dom->saveXML();
    }
}
